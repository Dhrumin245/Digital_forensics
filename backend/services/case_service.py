"""
Case service — US-01, US-02, US-03.

Business rules enforced here:
  - case_number is generated by DB trigger (CASE-YYYY-NNNNN)
  - Status transitions: open → active → closed → archived only
  - Closing a case requires at least one verified evidence item
  - Only LabTechnician or Examiner roles may be assigned to a case
  - Removing a user is blocked if they are the current evidence custodian
"""

from __future__ import annotations

from uuid import UUID

from fastapi import HTTPException, status
from sqlalchemy import func, select
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy.orm import selectinload

from models import Case, CaseAssignment, Evidence, User
from schemas import (
    CaseListResponse,
    CaseResponse,
    CaseStatus,
    CreateCaseRequest,
    UpdateCaseRequest,
    CaseAssignment as CaseAssignmentSchema,
)

# ── Helpers ───────────────────────────────────────────────────────────────────

ASSIGNABLE_ROLES = {"LabTechnician", "Examiner"}

VALID_TRANSITIONS: dict[str, list[str]] = {
    "open":   ["active"],
    "active": ["closed"],
    "closed": ["archived"],
}


def _assert_transition(current: str, target: str) -> None:
    if target not in VALID_TRANSITIONS.get(current, []):
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail={
                "error":   "invalid_status_transition",
                "message": f"Cannot transition from '{current}' to '{target}'. "
                           f"Valid next states: {VALID_TRANSITIONS.get(current, [])}",
            },
        )


def _to_response(case: Case) -> CaseResponse:
    return CaseResponse(
        id=case.id,
        case_number=case.case_number,
        title=case.title,
        description=case.description,
        status=CaseStatus(case.status),
        created_by=case.created_by,
        created_at=case.created_at,
        updated_at=case.updated_at,
        evidence_count=len(case.evidence) if case.evidence else 0,
        assignment_count=len(case.assignments) if case.assignments else 0,
    )


# ── US-01: Create case ────────────────────────────────────────────────────────

async def create_case(
    db:           AsyncSession,
    body:         CreateCaseRequest,
    created_by:   UUID,
) -> Case:
    case = Case(
        case_number="",                 # DB trigger fills this in
        title=body.title,
        description=body.description,
        reference_number=body.reference_number,
        status="open",
        created_by=created_by,
    )
    db.add(case)
    await db.flush()                    # Trigger fires → case_number is set
    await db.refresh(case)
    return case


# ── List cases ────────────────────────────────────────────────────────────────

async def list_cases(
    db:            AsyncSession,
    actor_id:      UUID,
    actor_role:    str,
    status_filter: str | None = None,
    page:          int = 1,
    page_size:     int = 20,
) -> CaseListResponse:
    """
    Admins and CaseManagers see all cases.
    Examiners and LabTechnicians see only assigned cases.
    """
    q = select(Case).options(
        selectinload(Case.assignments),
        selectinload(Case.evidence),
    )

    if actor_role not in {"Admin", "CaseManager"}:
        # Restrict to cases the user is assigned to
        q = q.join(CaseAssignment, CaseAssignment.case_id == Case.id).where(
            CaseAssignment.user_id == actor_id
        )

    if status_filter:
        q = q.where(Case.status == status_filter)

    total_q = select(func.count()).select_from(q.subquery())
    total   = (await db.execute(total_q)).scalar_one()

    q = q.offset((page - 1) * page_size).limit(page_size).order_by(Case.created_at.desc())
    cases = (await db.execute(q)).scalars().all()

    return CaseListResponse(
        items=[_to_response(c) for c in cases],
        total=total,
        page=page,
        page_size=page_size,
    )


# ── Get single case ───────────────────────────────────────────────────────────

async def get_case(db: AsyncSession, case_id: UUID, actor_id: UUID, actor_role: str) -> Case:
    result = await db.execute(
        select(Case)
        .options(selectinload(Case.assignments), selectinload(Case.evidence))
        .where(Case.id == case_id)
    )
    case = result.scalar_one_or_none()
    if not case:
        raise HTTPException(status_code=404, detail="Case not found")

    # Non-admin/non-manager: must be assigned
    if actor_role not in {"Admin", "CaseManager"}:
        assigned_ids = {a.user_id for a in case.assignments}
        if actor_id not in assigned_ids:
            raise HTTPException(status_code=403, detail="You are not assigned to this case")

    return case


# ── US-03: Update case / status transition ─────────────────────────────────────

async def update_case(
    db:      AsyncSession,
    case_id: UUID,
    body:    UpdateCaseRequest,
    actor_id: UUID,
) -> Case:
    case = await get_case(db, case_id, actor_id, "CaseManager")

    if body.status and body.status.value != case.status:
        _assert_transition(case.status, body.status.value)

        # Closing requires at least one verified evidence item
        if body.status.value == "closed":
            verified = [
                e for e in (case.evidence or [])
                if e.integrity_status == "verified"
            ]
            if not verified:
                raise HTTPException(
                    status_code=status.HTTP_400_BAD_REQUEST,
                    detail="Cannot close a case with no verified evidence items",
                )

        case.status = body.status.value

    if body.title:
        case.title = body.title
    if body.description is not None:
        case.description = body.description

    await db.flush()
    await db.refresh(case)
    return case


# ── US-02: Assign user ────────────────────────────────────────────────────────

async def assign_user(
    db:       AsyncSession,
    case_id:  UUID,
    user_id:  UUID,
    actor_id: UUID,
) -> CaseAssignment:
    # Verify case exists
    await get_case(db, case_id, actor_id, "CaseManager")

    # Verify user exists and has an assignable role
    user_result = await db.execute(select(User).where(User.id == user_id, User.is_active == True))
    user = user_result.scalar_one_or_none()
    if not user:
        raise HTTPException(status_code=404, detail="User not found or inactive")
    if user.role not in ASSIGNABLE_ROLES:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=f"Only {ASSIGNABLE_ROLES} roles can be assigned to cases. Got: {user.role}",
        )

    # Check not already assigned
    existing = await db.execute(
        select(CaseAssignment).where(
            CaseAssignment.case_id == case_id,
            CaseAssignment.user_id == user_id,
        )
    )
    if existing.scalar_one_or_none():
        raise HTTPException(status_code=409, detail="User already assigned to this case")

    assignment = CaseAssignment(
        case_id=case_id,
        user_id=user_id,
        assigned_by=actor_id,
    )
    db.add(assignment)
    await db.flush()
    await db.refresh(assignment)

    # Eager-load the user for the response
    result = await db.execute(
        select(CaseAssignment)
        .options(selectinload(CaseAssignment.user))
        .where(CaseAssignment.id == assignment.id)
    )
    return result.scalar_one()


async def list_assignments(db: AsyncSession, case_id: UUID) -> list[CaseAssignment]:
    result = await db.execute(
        select(CaseAssignment)
        .options(selectinload(CaseAssignment.user))
        .where(CaseAssignment.case_id == case_id)
    )
    return list(result.scalars().all())


async def remove_assignment(
    db:       AsyncSession,
    case_id:  UUID,
    user_id:  UUID,
    actor_id: UUID,
) -> None:
    # Block removal if user is current evidence custodian
    custodian_check = await db.execute(
        select(Evidence).where(
            Evidence.case_id == case_id,
            Evidence.current_custodian_id == user_id,
        )
    )
    held = custodian_check.scalars().first()
    if held:
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail=f"Cannot remove user — they are the active custodian of evidence '{held.filename}'. "
                   "Transfer custody first.",
        )

    result = await db.execute(
        select(CaseAssignment).where(
            CaseAssignment.case_id == case_id,
            CaseAssignment.user_id == user_id,
        )
    )
    assignment = result.scalar_one_or_none()
    if not assignment:
        raise HTTPException(status_code=404, detail="Assignment not found")

    await db.delete(assignment)
    await db.flush()
