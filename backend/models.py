"""
SQLAlchemy 2.0 ORM models.
All tables use UUIDs as primary keys.
Audit log table: no UPDATE or DELETE privileges granted to the app user.
Custody records: immutable once accepted — enforced at app layer + DB trigger.
"""

from __future__ import annotations

import uuid
from datetime import datetime
from typing import Optional

from sqlalchemy import (
    Boolean, DateTime, Enum, ForeignKey, Index, Integer,
    String, Text, func, UniqueConstraint,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship


def new_uuid() -> uuid.UUID:
    return uuid.uuid4()


class Base(DeclarativeBase):
    pass


# ─────────────────────────────────────────────────────────────────────────────
# USERS
# ─────────────────────────────────────────────────────────────────────────────

class User(Base):
    __tablename__ = "users"

    id:            Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=new_uuid)
    email:         Mapped[str]       = mapped_column(String(255), unique=True, nullable=False)
    full_name:     Mapped[str]       = mapped_column(String(200), nullable=False)
    role:          Mapped[str]       = mapped_column(String(50), nullable=False)
    password_hash: Mapped[str]       = mapped_column(String(255), nullable=False)
    is_active:     Mapped[bool]      = mapped_column(Boolean, default=True, nullable=False)
    created_at:    Mapped[datetime]  = mapped_column(DateTime(timezone=True), server_default=func.now())
    last_login_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)

    # Relationships — omit back_populates to avoid circular ambiguity with assigned_by FK


# ─────────────────────────────────────────────────────────────────────────────
# CASES — US-01, US-02, US-03
# ─────────────────────────────────────────────────────────────────────────────

class Case(Base):
    __tablename__ = "cases"

    id:               Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=new_uuid)
    case_number:      Mapped[str]       = mapped_column(String(50), unique=True, nullable=False)
    # Format: CASE-YYYY-NNNNN — generated by a DB sequence trigger
    title:            Mapped[str]       = mapped_column(String(300), nullable=False)
    description:      Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    reference_number: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)
    status:           Mapped[str]       = mapped_column(String(20), nullable=False, default="open")
    created_by:       Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), ForeignKey("users.id"), nullable=False)
    created_at:       Mapped[datetime]  = mapped_column(DateTime(timezone=True), server_default=func.now())
    updated_at:       Mapped[datetime]  = mapped_column(DateTime(timezone=True), server_default=func.now(), onupdate=func.now())

    # Relationships
    assignments: Mapped[list["CaseAssignment"]] = relationship(back_populates="case")
    evidence:    Mapped[list["Evidence"]]       = relationship(back_populates="case")
    tasks:       Mapped[list["Task"]]           = relationship(back_populates="case")
    reports:     Mapped[list["Report"]]         = relationship(back_populates="case")

    __table_args__ = (
        Index("ix_cases_status", "status"),
        Index("ix_cases_created_by", "created_by"),
    )


class CaseAssignment(Base):
    """
    US-02: Many-to-many between cases and users.
    Only LabTechnician and Examiner roles can be assigned.
    """
    __tablename__ = "case_assignments"

    id:          Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=new_uuid)
    case_id:     Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), ForeignKey("cases.id"), nullable=False)
    user_id:     Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), ForeignKey("users.id"), nullable=False)
    assigned_by: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), ForeignKey("users.id"), nullable=False)
    assigned_at: Mapped[datetime]  = mapped_column(DateTime(timezone=True), server_default=func.now())

    # Relationships
    case: Mapped["Case"] = relationship(back_populates="assignments", foreign_keys="CaseAssignment.case_id")
    user: Mapped["User"] = relationship(foreign_keys="CaseAssignment.user_id")

    __table_args__ = (
        UniqueConstraint("case_id", "user_id", name="uq_case_user_assignment"),
    )


# ─────────────────────────────────────────────────────────────────────────────
# EVIDENCE — US-04, US-05, US-06
# ─────────────────────────────────────────────────────────────────────────────

class Evidence(Base):
    """
    Core evidence record. sha256_hash is ALWAYS computed server-side.
    hash_source distinguishes uploaded vs imported hashes.
    Records are immutable — no UPDATE to sha256_hash or uploaded_at is permitted.
    """
    __tablename__ = "evidence"

    id:                   Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=new_uuid)
    case_id:              Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), ForeignKey("cases.id"), nullable=False)
    filename:             Mapped[str]       = mapped_column(String(500), nullable=False)
    file_size_bytes:      Mapped[int]       = mapped_column(Integer, nullable=False)
    mime_type:            Mapped[str]       = mapped_column(String(200), nullable=False)
    evidence_type:        Mapped[str]       = mapped_column(String(50), nullable=False)
    sha256_hash:          Mapped[str]       = mapped_column(String(64), nullable=False)
    # Storage key in MinIO/S3 where the raw file lives
    storage_key:          Mapped[str]       = mapped_column(String(500), nullable=False)
    hash_source:          Mapped[str]       = mapped_column(String(20), nullable=False, default="computed")
    # "computed" = server-side on upload | "imported" = from external tool CSV/JSON
    acquisition_tool:     Mapped[Optional[str]] = mapped_column(String(200), nullable=True)
    description:          Mapped[str]       = mapped_column(Text, nullable=False)
    acquisition_notes:    Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    uploaded_by:          Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), ForeignKey("users.id"), nullable=False)
    uploaded_at:          Mapped[datetime]  = mapped_column(DateTime(timezone=True), server_default=func.now())
    current_custodian_id: Mapped[Optional[uuid.UUID]] = mapped_column(UUID(as_uuid=True), ForeignKey("users.id"), nullable=True)
    integrity_status:     Mapped[str]       = mapped_column(String(20), nullable=False, default="pending")

    # Relationships
    case:           Mapped["Case"]           = relationship(back_populates="evidence")
    custody_records: Mapped[list["CustodyRecord"]] = relationship(back_populates="evidence")

    __table_args__ = (
        Index("ix_evidence_case_id", "case_id"),
        Index("ix_evidence_sha256", "sha256_hash"),  # Critical — verification portal queries by hash
    )


# ─────────────────────────────────────────────────────────────────────────────
# CUSTODY CHAIN — US-07, US-08
# ─────────────────────────────────────────────────────────────────────────────

class CustodyRecord(Base):
    """
    Append-only chain of custody. Once status = 'accepted', the record
    is IMMUTABLE — enforced by DB trigger (no UPDATE privilege on this table
    for the app DB user once status != 'pending').
    hash_at_transfer stores the SHA-256 at the moment of transfer — proves
    evidence was intact at the point of handoff.
    """
    __tablename__ = "custody_records"

    id:               Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=new_uuid)
    evidence_id:      Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), ForeignKey("evidence.id"), nullable=False)
    from_user_id:     Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), ForeignKey("users.id"), nullable=False)
    to_user_id:       Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), ForeignKey("users.id"), nullable=False)
    transfer_reason:  Mapped[str]       = mapped_column(Text, nullable=False)
    hash_at_transfer: Mapped[str]       = mapped_column(String(64), nullable=False)
    status:           Mapped[str]       = mapped_column(String(20), nullable=False, default="pending")
    initiated_at:     Mapped[datetime]  = mapped_column(DateTime(timezone=True), server_default=func.now())
    accepted_at:      Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    from_signature:   Mapped[str]       = mapped_column(Text, nullable=False)
    to_signature:     Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    # Relationships
    evidence:  Mapped["Evidence"] = relationship(back_populates="custody_records")
    from_user: Mapped["User"]     = relationship(foreign_keys=[from_user_id])
    to_user:   Mapped["User"]     = relationship(foreign_keys=[to_user_id])

    __table_args__ = (
        Index("ix_custody_evidence_id", "evidence_id"),
    )


