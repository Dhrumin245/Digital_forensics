class ReportVersion(Base):
    """
    US-11: Every save creates a NEW row — never overwrites.
    content_hash is computed server-side on the content string.
    is_court_ready=True rows are IMMUTABLE — enforced by DB trigger.
    Deletion is not permitted for any row.
    """
    __tablename__ = "report_versions"

    id:             Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=new_uuid)
    report_id:      Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), ForeignKey("reports.id"), nullable=False)
    version_number: Mapped[int]       = mapped_column(Integer, nullable=False)
    content:        Mapped[str]       = mapped_column(Text, nullable=False)
    content_hash:   Mapped[str]       = mapped_column(String(64), nullable=False)
    author_id:      Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), ForeignKey("users.id"), nullable=False)
    saved_at:       Mapped[datetime]  = mapped_column(DateTime(timezone=True), server_default=func.now())
    change_summary: Mapped[str]       = mapped_column(String(500), nullable=False)
    is_court_ready: Mapped[bool]      = mapped_column(Boolean, default=False, nullable=False)
    locked_by:      Mapped[Optional[uuid.UUID]] = mapped_column(UUID(as_uuid=True), ForeignKey("users.id"), nullable=True)
    locked_at:      Mapped[Optional[datetime]]  = mapped_column(DateTime(timezone=True), nullable=True)
    review_notes:   Mapped[Optional[str]]       = mapped_column(Text, nullable=True)

    # Relationships
    report: Mapped["Report"] = relationship(back_populates="versions")
    author: Mapped["User"]   = relationship(foreign_keys=[author_id])

    __table_args__ = (
        UniqueConstraint("report_id", "version_number", name="uq_report_version"),
        Index("ix_report_versions_report_id", "report_id"),
    )


