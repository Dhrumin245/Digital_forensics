# ─────────────────────────────────────────────────────────────────────────────
# AUDIT LOG — US-15
# ─────────────────────────────────────────────────────────────────────────────

class AuditLog(Base):
    """
    IMMUTABLE append-only log. The app DB user has NO UPDATE or DELETE
    privilege on this table — enforced at the PostgreSQL role level.
    Schema: forensics_audit (separate schema, restricted permissions).

    Every write operation in the system produces exactly one row here.
    Rows are also mirrored to S3 (forensics-audit-mirror bucket, Object Lock ON)
    via Kafka consumer — so even a compromised DB cannot erase evidence.
    """
    __tablename__ = "audit_log"
    __table_args__ = {"schema": "forensics_audit"}

    id:            Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=new_uuid)
    actor_id:      Mapped[Optional[uuid.UUID]] = mapped_column(UUID(as_uuid=True), nullable=True)
    # Null for unauthenticated actions (e.g. public verify portal)
    actor_role:    Mapped[Optional[str]] = mapped_column(String(50), nullable=True)
    action_type:   Mapped[str]       = mapped_column(String(100), nullable=False)
    resource_type: Mapped[str]       = mapped_column(String(50), nullable=False)
    resource_id:   Mapped[str]       = mapped_column(String(100), nullable=False)
    ip_address:    Mapped[str]       = mapped_column(String(45), nullable=False)  # IPv6 max length
    result:        Mapped[str]       = mapped_column(String(20), nullable=False)  # success|failure|blocked
    detail:        Mapped[dict]      = mapped_column(JSONB, nullable=False, default=dict)
    timestamp:     Mapped[datetime]  = mapped_column(DateTime(timezone=True), server_default=func.now(), index=True)

    # Indexes for common query patterns
    __table_args__ = (
        Index("ix_audit_actor_id",    "actor_id"),
        Index("ix_audit_action_type", "action_type"),
        Index("ix_audit_resource_id", "resource_id"),
        Index("ix_audit_timestamp",   "timestamp"),
        {"schema": "forensics_audit"},
    )
